"""Pydantic domain contracts for hosted language model integration.

Defines schemas for:
- Place proposals generated by language model discovery
- Research requests and structured responses
- Ranking requests and scored candidates
- Provider configuration options
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class DayOpeningHours(BaseModel):
    """Structured visiting hours for a single day of the week."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    day: str = Field(..., description="Day name (e.g. monday, tuesday)")
    opens: str = Field(..., description="Opening time in HH:MM format (e.g. 09:00)")
    closes: str = Field(..., description="Closing time in HH:MM format (e.g. 18:00)")
    is_closed: bool = Field(
        default=False, description="Flag indicating place is closed on this day"
    )


class StructuredOpeningHours(BaseModel):
    """Weekly schedule model representing opening hours across days."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    days: list[DayOpeningHours] = Field(default_factory=list, description="Day schedules")
    raw_text: str | None = Field(default=None, description="Original human readable hours string")


class PlaceProposal(BaseModel):
    """Generative place proposal emitted during discovery research."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    name: str = Field(..., min_length=1, description="Common name of proposed point of interest")
    category: str = Field(
        ...,
        min_length=1,
        description="Place category (e.g. restaurant, street_food, heritage, nature, museum)",
    )
    estimated_latitude: float = Field(
        ...,
        ge=-90.0,
        le=90.0,
        description="Estimated latitude coordinate",
    )
    estimated_longitude: float = Field(
        ...,
        ge=-180.0,
        le=180.0,
        description="Estimated longitude coordinate",
    )
    description: str = Field(
        default="",
        description="Descriptive summary or traveler highlight",
    )
    fit_score: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Match score between place and brief preferences",
    )
    suggested_stay_minutes: int = Field(
        default=60,
        ge=5,
        le=1440,
        description="Recommended dwell time in minutes",
    )
    price_estimate_inr: float | None = Field(
        default=None,
        ge=0.0,
        description="Estimated entry fee or meal price in Indian Rupees",
    )
    uncertainty: str = Field(
        default="EDITORIAL_DISCOVERY",
        description="Provenance uncertainty label",
    )
    is_candidate: bool = Field(
        default=True,
        description="Flag indicating proposal has not yet passed deterministic verification",
    )
    opening_hours: str | None = Field(
        default=None,
        description="Reported or assumed visiting hours description",
    )
    structured_hours: StructuredOpeningHours | None = Field(
        default=None,
        description="Optional structured opening hours across days for deterministic scheduling",
    )
    address: str | None = Field(
        default=None,
        description="Approximate address or landmark description",
    )


class RankedPlace(BaseModel):
    """Candidate place with priority rank and selection rationale."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    place: PlaceProposal = Field(..., description="Underlying place candidate")
    rank: int = Field(..., ge=1, description="Priority ordering index starting at 1")
    fit_score: float = Field(..., ge=0.0, le=1.0, description="Evaluated fit score")
    selection_rationale: str = Field(
        default="",
        description="Explanation for selecting or prioritizing this place",
    )


class ResearchRequest(BaseModel):
    """Input payload for corridor place discovery."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    brief_summary: str = Field(..., min_length=1, description="Concise brief description")
    origin_name: str = Field(..., min_length=1, description="Origin city or starting hub")
    destination_names: list[str] = Field(
        ...,
        min_length=1,
        description="Destination cities or principal anchor stops",
    )
    traveler_preferences: list[str] = Field(
        default_factory=list,
        description="Interest keywords (e.g. food, heritage, architecture, nature)",
    )
    budget_tier: str = Field(
        default="MODERATE",
        description="Budget tier (BUDGET, MODERATE, LUXURY)",
    )
    transport_mode: str = Field(
        default="car_petrol",
        description="Primary transport mode for corridor alignment",
    )
    corridor_distance_km_limit: float = Field(
        default=100.0,
        ge=0.0,
        description="Maximum distance from origin-destination corridor line",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Optional execution context metadata",
    )


class ResearchResponse(BaseModel):
    """Output payload from place discovery research."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    candidate_places: list[PlaceProposal] = Field(
        default_factory=list,
        description="List of proposed candidate places along corridor",
    )
    regional_travel_notes: list[str] = Field(
        default_factory=list,
        description="Contextual driving, dining, or seasonal advisories",
    )
    recommended_pace: str = Field(
        default="MODERATE",
        description="Suggested itinerary pace",
    )
    provider: str = Field(
        default="fixture",
        description="Name of language model client adapter that generated response",
    )


class RankingRequest(BaseModel):
    """Input payload for scoring and ordering candidate places."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    candidate_places: list[PlaceProposal] = Field(
        default_factory=list,
        description="Candidates to be evaluated and prioritized",
    )
    trip_brief: dict[str, Any] = Field(
        default_factory=dict,
        description="Serialized travel brief or constraints",
    )
    traveler_constraints: list[str] = Field(
        default_factory=list,
        description="Explicit traveler constraints (e.g. must finish by 18:00, vegetarian only)",
    )
    max_places_to_select: int = Field(
        default=10,
        ge=1,
        description="Maximum number of candidates to select",
    )


class RankingResponse(BaseModel):
    """Output payload from candidate place ranking."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    ranked_places: list[RankedPlace] = Field(
        default_factory=list,
        description="Prioritized list of selected places",
    )
    eliminated_candidates: list[dict[str, str]] = Field(
        default_factory=list,
        description="Candidates excluded with explanation reasons",
    )
    overall_pacing_evaluation: str = Field(
        default="",
        description="Evaluation of feasible stops for the requested duration",
    )
    provider: str = Field(
        default="fixture",
        description="Name of language model client adapter that performed ranking",
    )


class LlmProviderConfig(BaseModel):
    """Configuration model for language model adapters."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    provider: str = Field(
        default="fixture",
        description="Provider identifier (fixture, bedrock, anthropic, openai)",
    )
    timeout_seconds: float = Field(
        default=15.0,
        ge=1.0,
        le=120.0,
        description="Request socket timeout in seconds",
    )
    max_retries: int = Field(
        default=2,
        ge=0,
        le=5,
        description="Maximum retry attempts on transient failures",
    )
    model_id: str | None = Field(
        default=None,
        description="Optional model identifier string",
    )
    api_key: str | None = Field(
        default=None,
        description="Optional API key for direct hosted providers",
    )
    region: str = Field(
        default="ap-south-1",
        description="AWS region name when using Bedrock",
    )
